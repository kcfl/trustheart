"""Model selection heuristic: Simplest model within 1 Standard Error of the best."""

from collections.abc import Sequence
import numpy as np

from ml.search_space import Config, complexity_key


def select_config(scores: dict[str, np.ndarray], configs: Sequence[Config]) -> Config:
    """Select the simplest configuration within 1 Standard Error of the best mean score.

    Selection Rule ('1-SE Rule' / Breiman et al. heuristic):
    1. Compute the mean score for each candidate configuration across inner folds.
    2. Identify the configuration with the highest mean inner score (the 'best' config).
    3. Compute the standard error of the best configuration's fold scores:
           SE_best = std(scores[best_config], ddof=1) / sqrt(n)
       where n is the number of inner fold scores.
    4. Construct the eligible candidate set:
           eligible = {c in configs | mean(c) >= mean(best_config) - SE_best}
    5. Return the configuration in the eligible set having the lowest complexity_key.

    Methodological Limitation:
    Fold scores generated by cross-validation (especially repeated cross-validation)
    are correlated because subsets of the training data overlap across folds. Therefore,
    SE_best is not a formal independent-sample standard error, but rather an empirical,
    conservative regularization heuristic to guard against overfitting to validation noise.

    Parameters
    ----------
    scores : dict[str, np.ndarray]
        Mapping from configuration name to array of fold validation scores (e.g. 6 inner ROC-AUCs).
    configs : Sequence[Config]
        Eligible configurations to consider for selection.

    Returns
    -------
    Config
        Selected configuration satisfying the 1-SE simplicity criterion.

    Raises
    ------
    ValueError
        If configs is empty or a config has no matching scores.
    """
    if not configs:
        raise ValueError("Cannot select configuration from an empty configs sequence.")

    for c in configs:
        if c.name not in scores:
            raise ValueError(f"Missing inner validation scores for config '{c.name}'.")

    # 1. Compute mean for each config
    config_means = {c.name: float(np.mean(scores[c.name])) for c in configs}

    # 2. Find best config (tie-breaker: lowest complexity)
    best_config = max(
        configs,
        key=lambda c: (config_means[c.name], -complexity_key(c)[0]),
    )
    best_mean = config_means[best_config.name]

    # 3. Compute SE of best config
    best_scores = np.asarray(scores[best_config.name])
    n = len(best_scores)
    if n > 1:
        se_best = float(np.std(best_scores, ddof=1) / np.sqrt(n))
    else:
        se_best = 0.0

    # 4. Form eligible set within 1 SE of best_mean
    threshold = best_mean - se_best
    eligible = [c for c in configs if config_means[c.name] >= threshold]

    # 5. Pick simplest eligible config
    selected_config = min(eligible, key=complexity_key)
    return selected_config
