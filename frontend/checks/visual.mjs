import { chromium } from '@playwright/test';
import fs from 'node:fs';
const browser = await chromium.launch({headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
page.on('pageerror',e=>console.log('PAGE ERROR',e.message));
page.on('console',m=>{if(m.type()==='error')console.log('CONSOLE ERROR',m.text())});
await page.goto('http://localhost:5173');
await page.getByRole('button',{name:'Rotate heart',exact:true}).waitFor();
await page.waitForFunction(()=>!document.querySelector('button[aria-label="Rotate heart"]')?.disabled,{timeout:30000});
await page.waitForTimeout(1400);
await page.screenshot({path:'checks/home-desktop.png'});
const data=await page.locator('canvas').evaluate(el=>el.toDataURL('image/png'));
fs.writeFileSync('public/heart-fallback.png',Buffer.from(data.split(',')[1],'base64'));
console.log('canvas',await page.locator('canvas').boundingBox());
console.log('overflow',await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth})));
await page.setViewportSize({width:390,height:844});
await page.waitForTimeout(700);
await page.screenshot({path:'checks/home-mobile.png',fullPage:true});
await browser.close();
