import { chromium } from '@playwright/test';
import fs from 'node:fs';
const browser = await chromium.launch({headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader']});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
page.on('pageerror', e=>console.log('ERROR',e.message));
await page.goto('http://localhost:5173/');
await page.getByRole('button',{name:'Rotate heart',exact:true}).waitFor();
await page.waitForFunction(()=>!document.querySelector('button[aria-label="Rotate heart"]')?.disabled, {timeout:30000});
console.log('Sky:',await page.locator('[data-nebula-state]').getAttribute('data-nebula-state'));
await page.getByRole('button',{name:'Pause background animation',exact:true}).click();
await page.waitForTimeout(1200);
await page.screenshot({path:'checks/glass-hero.png'});
const canvas = page.locator('.three-mount canvas');
const data = await canvas.evaluate(el=>el.toDataURL('image/png'));
fs.writeFileSync('public/heart-fallback.png',Buffer.from(data.split(',')[1],'base64'));
await page.evaluate(()=>window.scrollTo({top:930,behavior:'instant'}));
await page.waitForTimeout(1300);
await page.screenshot({path:'checks/glass-cards.png'});
console.log('depth cards:',await page.locator('[data-depth]').count());
await page.setViewportSize({width:390,height:844});
await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));await page.waitForTimeout(700);
await page.screenshot({path:'checks/glass-mobile.png'});
await browser.close();
