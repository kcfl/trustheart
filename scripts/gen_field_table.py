#!/usr/bin/env python3
"""Generates docs/FIELD_MAP.md from backend/app/schemas.py and backend/app/config.py."""

from pathlib import Path
import sys

# Ensure repository root is on sys.path
REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from backend.app.config import FEATURE_GROUPS, FULL_HUMAN_FEATURES, QUICK_FEATURES
from backend.app.schemas import BINARY_FEATURES, HARD_FEATURE_RANGES
from ml.config import VHD_ORDINAL_MAPPING

def generate_field_map() -> str:
    lines = [
        "# TrustHeart 3D — Feature Mapping and Schema Contract",
        "",
        "> This document is automatically generated by `scripts/gen_field_table.py` from `backend/app/schemas.py` and `backend/app/config.py`.",
        "> Do not edit this file by hand.",
        "",
        "## Feature Contract Table (All 54 Multimodal Features)",
        "",
        "| # | Backend Feature Name | Clinical Group | Type | Allowed Values / HARD_FEATURE_RANGES | Mode | Form Key / Control |",
        "|---|---|---|---|---|---|---|",
    ]

    # Invert FEATURE_GROUPS to find group for each feature
    feature_to_group = {}
    for group, feats in FEATURE_GROUPS.items():
        for f in feats:
            feature_to_group[f] = group

    seen = set()
    rows = []

    for idx, feat in enumerate(FULL_HUMAN_FEATURES, 1):
        if feat in seen:
            continue
        seen.add(feat)

        group = feature_to_group.get(feat, "Other")
        is_quick = feat in QUICK_FEATURES
        mode_str = "Quick & Full" if is_quick else "Full only"

        # Determine type & allowed values / range
        if feat in BINARY_FEATURES:
            feat_type = "Binary"
            allowed_range = "0 or 1 (boolean / Y / N)"
        elif feat in HARD_FEATURE_RANGES:
            min_val, max_val = HARD_FEATURE_RANGES[feat]
            if feat in ("Region RWMA", "Function Class"):
                feat_type = "Ordinal integer"
                allowed_range = f"[{int(min_val)}, {int(max_val)}]"
            else:
                feat_type = "Continuous float"
                allowed_range = f"[{min_val:.1f}, {max_val:.1f}]"
        elif feat == "Sex":
            feat_type = "Categorical"
            allowed_range = "Male, Female"
        elif feat == "BBB":
            feat_type = "Categorical"
            allowed_range = "N, LBBB, RBBB"
        elif feat == "VHD":
            feat_type = "Categorical (Ordinal)"
            allowed_range = "N, mild, Moderate, Severe"
        else:
            feat_type = "Unknown"
            allowed_range = "Unspecified"

        # Form control mapping
        if feat in ("Typical Chest Pain", "Atypical", "Nonanginal"):
            form_control = "chestPain select (None / Typical / Atypical / Non-anginal)"
        elif feat == "Sex":
            form_control = "Sex select (Male / Female)"
        elif feat == "BBB":
            form_control = "BBB select (N / LBBB / RBBB)"
        elif feat == "VHD":
            form_control = "VHD select (N / mild / Moderate / Severe)"
        elif feat_type == "Binary":
            form_control = f"{feat} select (Yes / No)"
        else:
            form_control = f"{feat} smooth numeric input"

        lines.append(
            f"| {idx} | `{feat}` | {group} | {feat_type} | {allowed_range} | {mode_str} | {form_control} |"
        )

    lines.extend([
        "",
        "## Summary Statistics",
        f"- **Total human-readable multimodal features**: {len(FULL_HUMAN_FEATURES)}",
        f"- **Total distinct features defined**: {len(seen)}",
        f"- **Quick mode screening features**: {len(QUICK_FEATURES)} ({', '.join(QUICK_FEATURES)})",
        f"- **Continuous & ordinal range-checked features**: {len(HARD_FEATURE_RANGES)}",
        f"- **Binary features**: {len(BINARY_FEATURES)}",
        f"- **Categorical features**: 3 (`Sex`, `BBB`, `VHD`)",
        "",
        "## Casing and Name Discrepancy Audit",
        "Frontend forms must strictly match backend Pydantic field names. Below is the strict naming record:",
        "- `CR` (Serum Creatinine): Backend requires uppercase `CR`, not `Cr` or `creatinine`.",
        "- `HB` (Hemoglobin): Backend requires uppercase `HB`, not `Hb` or `hemoglobin`.",
        "- `DLP` (Dyslipidemia): Backend requires uppercase `DLP`, not `DL` or `dyslipidemia`.",
        "- `CRF` (Chronic Renal Failure): Backend requires uppercase `CRF`.",
        "- `CVA` (Cerebrovascular Accident): Backend requires uppercase `CVA`.",
        "- `BP` (Blood Pressure): Backend requires `BP`, not `systolic`.",
        "- `Chol`: Note: `Chol` is NOT a feature in `FULL_HUMAN_FEATURES` (the dataset has `LDL`, `HDL`, `TG`, but no bare `Chol` column; bare cholesterol was a legacy demo field).",
        "- `VHD` (Valvular Heart Disease): Backend expects casing among `['N', 'mild', 'Moderate', 'Severe']` (case-insensitive parsed to ordinal 0..3).",
        "- `BBB` (Bundle Branch Block): Backend expects exact uppercase among `['N', 'LBBB', 'RBBB']`.",
        "- `Sex`: Backend expects exact title-case `Male` or `Female`.",
        "- `Exertional CP`: Dropped constant column; explicitly forbidden from model inputs and rejected by `/api/predict` with HTTP 422.",
    ])

    return "\n".join(lines) + "\n"

def main():
    content = generate_field_map()
    out_path = REPO_ROOT / "docs" / "FIELD_MAP.md"
    out_path.write_text(content, encoding="utf-8")
    print(f"Generated {out_path} ({len(FULL_HUMAN_FEATURES)} features).")
    print(content)

if __name__ == "__main__":
    main()
